namespace TrakHound
{
    /// <summary>
    /// The order to sort results in
    /// </summary>
    public enum TrakHoundSortOrder
    {
        /// <summary>
        /// Sort from lowest to highest (oldest to newest)
        /// </summary>
        Ascending = 1,

        /// <summary>
        /// Sort from highest to lowest (newest to oldest)
        /// </summary>
        Descending = -1
    }
}
